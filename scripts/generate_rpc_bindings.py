    lines.append("        auto it = handlers_.find(serial_id);")
    lines.append("        if (it == handlers_.end()) {")
    lines.append("            return corpcron::RpcDispatcher::error(UNKNOWN_METHOD,")
    lines.append("                                                  \"Unknown serial_id: \" + std::to_string(serial_id));")
    lines.append("        }")
    lines.append("        return it->second(payload);")
    lines.append("    }")
    lines.append("")
    lines.append("    corpcron::RpcStreamResult dispatchStream(uint32_t serial_id, const std::string& payload) const {")
    lines.append("        auto it = stream_handlers_.find(serial_id);")
    lines.append("        if (it != stream_handlers_.end()) return it->second(payload);")
    lines.append("        return corpcron::RpcStreamResult{{dispatch(serial_id, payload)}};")
    lines.append("    }")
    lines.append("")
    lines.append("    template <typename Request, typename Response>")
    lines.append("    void registerServerStream(uint32_t request_serial_id, uint32_t response_serial_id,")
    lines.append("                              std::function<std::vector<Response>(const Request&)> handler) {")
