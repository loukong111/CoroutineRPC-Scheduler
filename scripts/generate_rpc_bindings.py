#!/usr/bin/env python3
from pathlib import Path
import re
import tempfile

ROOT = Path(__file__).resolve().parents[1]
PROTO = ROOT / "proto" / "rpc.proto"
OUT = ROOT / "generated" / "rpc_service.hpp"


def parse_service(proto_text):
    service_match = re.search(r"service\s+CorpCronRpc\s*\{(?P<body>.*?)\n\}", proto_text, re.S)
    if not service_match:
        raise RuntimeError("service CorpCronRpc not found in proto/rpc.proto")
    body = service_match.group("body")
    pattern = re.compile(
        r"rpc\s+(\w+)\s*\(\s*(\w+)\s*\)\s*returns\s*\(\s*(stream\s+)?(\w+)\s*\)\s*;")
    methods = [
        {
            "name": method,
            "request": req,
            "response": resp,
            "server_streaming": bool(stream),
        }
        for method, req, stream, resp in pattern.findall(body)
    ]
    if not methods:
        raise RuntimeError("no rpc methods found in service CorpCronRpc")
    return methods


def write_header(methods):
    lines = []
    lines.append("// Generated by scripts/generate_rpc_bindings.py. Do not edit manually.")
