    lines.append("                responses.push_back(response);")
    lines.append("            }")
    lines.append("            for (auto& response : responses) response.set_end_of_stream(false);")
    lines.append("            responses.back().set_end_of_stream(true);")
    lines.append("            corpcron::RpcStreamResult result;")
    lines.append("            result.responses.reserve(responses.size());")
    lines.append("            for (const auto& response : responses) {")
    lines.append("                std::string response_payload;")
    lines.append("                if (!response.SerializeToString(&response_payload)) {")
    lines.append("                    return corpcron::RpcStreamResult{{")
    lines.append("                        corpcron::RpcDispatcher::error(INTERNAL_ERROR, \"serialize response failed\")}};")
    lines.append("                }")
    lines.append("                result.responses.push_back({response_serial_id, std::move(response_payload)});")
    lines.append("            }")
    lines.append("            return result;")
    lines.append("        };")
    lines.append("    }")
    lines.append("")
    lines.append("private:")
    lines.append("    template <typename Request, typename Response>")
    lines.append("    void registerUnary(uint32_t request_serial_id, uint32_t response_serial_id,")
    lines.append("                       std::function<Response(const Request&)> handler) {")
    lines.append("        handlers_[request_serial_id] = [response_serial_id, handler = std::move(handler)]")
    lines.append("            (const std::string& payload) -> corpcron::RpcResponse {")
    lines.append("            Request request;")
    lines.append("            if (!request.ParseFromString(payload)) {")
    lines.append("                return corpcron::RpcDispatcher::error(BAD_REQUEST, \"parse request failed\");")
    lines.append("            }")
    lines.append("            Response response = handler(request);")
    lines.append("            std::string response_payload;")
    lines.append("            response.SerializeToString(&response_payload);")
    lines.append("            return corpcron::RpcResponse{response_serial_id, response_payload};")
    lines.append("        };")
    lines.append("    }")
    lines.append("")
    lines.append("    std::unordered_map<uint32_t, RawHandler> handlers_;")
