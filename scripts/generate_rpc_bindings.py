    lines.append("inline constexpr RpcMethodDescriptor kCorpCronRpcMethods[] = {")
    for item in methods:
        method = item["name"]
        req = item["request"]
        resp = item["response"]
        lines.append(
            f"    {{\"{method}\", k{method}RequestSerialId, k{method}ResponseSerialId, "
            f"\"{req}\", \"{resp}\"}},")
    lines.append("};")
    lines.append("")
    lines.append("inline const RpcMethodDescriptor* findMethodByRequestSerialId(uint32_t serial_id) {")
    lines.append("    for (const auto& method : kCorpCronRpcMethods) {")
    lines.append("        if (method.request_serial_id == serial_id) return &method;")
    lines.append("    }")
    lines.append("    return nullptr;")
    lines.append("}")
    lines.append("")
    lines.append("inline const RpcMethodDescriptor* findMethodByName(const std::string& name) {")
    lines.append("    for (const auto& method : kCorpCronRpcMethods) {")
    lines.append("        if (name == method.name) return &method;")
    lines.append("    }")
    lines.append("    return nullptr;")
    lines.append("}")
    lines.append("")
    lines.append("class CorpCronRpcStub {")
    lines.append("public:")
    lines.append("    explicit CorpCronRpcStub(corpcron::RpcClient& client, std::string auth_token = {})")
    lines.append("        : client_(client), auth_token_(std::move(auth_token)) {}")
    lines.append("")
    lines.append("    void setAuthToken(std::string auth_token) { auth_token_ = std::move(auth_token); }")
    lines.append("")
    for item in methods:
        method = item["name"]
        req = item["request"]
        resp = item["response"]
        if item["server_streaming"]:
            lines.append(f"    bool {method}({req}& request, std::function<bool(const {resp}&)> on_response,")
            lines.append("              std::string* error = nullptr, int timeout_ms = 3000) {")
            lines.append(f"        return callStream<{req}, {resp}>(k{method}RequestSerialId,")
            lines.append(f"                                      k{method}ResponseSerialId,")
            lines.append("                                      request, std::move(on_response), error, timeout_ms);")
            lines.append("    }")
            lines.append("")
            continue
        lines.append(f"    bool {method}({req}& request, {resp}& response,")
        lines.append("              std::string* error = nullptr, int timeout_ms = 3000) {")
        lines.append(f"        return call<{req}, {resp}>(k{method}RequestSerialId,")
        lines.append(f"                                      k{method}ResponseSerialId,")
        lines.append("                                      request, response, error, timeout_ms);")
        lines.append("    }")
        lines.append("")
    lines.append("private:")
    lines.append("    template <typename Request, typename Response>")
    lines.append("    bool call(uint32_t request_serial_id, uint32_t expected_response_serial_id,")
    lines.append("              Request& request, Response& response, std::string* error, int timeout_ms) {")
    lines.append("        if (error) error->clear();")
    lines.append("        if (!auth_token_.empty() && request.auth_token().empty()) {")
    lines.append("            request.set_auth_token(auth_token_);")
    lines.append("        }")
    lines.append("        std::string request_payload;")
    lines.append("        if (!request.SerializeToString(&request_payload)) {")
    lines.append("            if (error) *error = \"serialize request failed\";")
    lines.append("            return false;")
    lines.append("        }")
    lines.append("        uint32_t response_serial_id = 0;")
    lines.append("        std::string response_payload;")
    lines.append("        if (!client_.call(request_serial_id, request_payload, response_serial_id, response_payload, timeout_ms)) {")
    lines.append("            if (error) *error = client_.lastError().empty() ? \"rpc transport failed\" : client_.lastError();")
    lines.append("            return false;")
    lines.append("        }")
    lines.append("        if (response_serial_id == kRpcErrorSerialId) {")
    lines.append("            RpcError rpc_error;")
    lines.append("            if (rpc_error.ParseFromString(response_payload)) {")
    lines.append("                if (error) *error = rpc_error.message();")
    lines.append("            } else if (error) {")
    lines.append("                *error = \"parse RpcError failed\";")
    lines.append("            }")
    lines.append("            return false;")
    lines.append("        }")
    lines.append("        if (response_serial_id != expected_response_serial_id) {")
    lines.append("            if (error) *error = \"unexpected response serial_id: \" + std::to_string(response_serial_id);")
    lines.append("            return false;")
    lines.append("        }")
    lines.append("        if (!response.ParseFromString(response_payload)) {")
    lines.append("            if (error) *error = \"parse response failed\";")
    lines.append("            return false;")
    lines.append("        }")
    lines.append("        return true;")
    lines.append("    }")
    lines.append("")
    lines.append("    template <typename Request, typename Response>")
    lines.append("    bool callStream(uint32_t request_serial_id, uint32_t expected_response_serial_id,")
    lines.append("                    Request& request, std::function<bool(const Response&)> on_response,")
    lines.append("                    std::string* error, int timeout_ms) {")
    lines.append("        if (error) error->clear();")
    lines.append("        if (!auth_token_.empty() && request.auth_token().empty()) {")
    lines.append("            request.set_auth_token(auth_token_);")
    lines.append("        }")
    lines.append("        std::string request_payload;")
    lines.append("        if (!request.SerializeToString(&request_payload)) {")
    lines.append("            if (error) *error = \"serialize request failed\";")
    lines.append("            return false;")
    lines.append("        }")
    lines.append("        bool saw_end = false;")
    lines.append("        bool ok = client_.callStream(request_serial_id, request_payload,")
    lines.append("            [&](uint32_t response_serial_id, const std::string& response_payload) {")
    lines.append("                if (response_serial_id == kRpcErrorSerialId) {")
    lines.append("                    RpcError rpc_error;")
    lines.append("                    if (rpc_error.ParseFromString(response_payload)) {")
    lines.append("                        if (error) *error = rpc_error.message();")
    lines.append("                    } else if (error) {")
    lines.append("                        *error = \"parse RpcError failed\";")
    lines.append("                    }")
    lines.append("                    return false;")
    lines.append("                }")
    lines.append("                if (response_serial_id != expected_response_serial_id) {")
    lines.append("                    if (error) *error = \"unexpected stream response serial_id: \" + std::to_string(response_serial_id);")
    lines.append("                    return false;")
    lines.append("                }")
    lines.append("                Response response;")
    lines.append("                if (!response.ParseFromString(response_payload)) {")
    lines.append("                    if (error) *error = \"parse stream response failed\";")
    lines.append("                    return false;")
    lines.append("                }")
    lines.append("                saw_end = response.end_of_stream();")
    lines.append("                if (on_response && !on_response(response)) return false;")
    lines.append("                return !saw_end;")
    lines.append("            }, timeout_ms);")
    lines.append("        if (!ok && error && error->empty()) *error = \"rpc stream transport failed\";")
    lines.append("        return ok && saw_end;")
    lines.append("    }")
    lines.append("")
    lines.append("    corpcron::RpcClient& client_;")
    lines.append("    std::string auth_token_;")
    lines.append("};")
    lines.append("")
    lines.append("class CorpCronRpcSkeleton {")
    lines.append("public:")
    lines.append("    using RawHandler = std::function<corpcron::RpcResponse(const std::string&)>;")
    lines.append("    using RawStreamHandler = std::function<corpcron::RpcStreamResult(const std::string&)>;")
    lines.append("")
    for item in methods:
        method = item["name"]
        req = item["request"]
        resp = item["response"]
        if item["server_streaming"]:
            lines.append(f"    void register{method}(std::function<std::vector<{resp}>(const {req}&)> handler) {{")
            lines.append(f"        registerServerStream<{req}, {resp}>(k{method}RequestSerialId,")
            lines.append(f"                                      k{method}ResponseSerialId, std::move(handler));")
            lines.append("    }")
            lines.append("")
            continue
        lines.append(f"    void register{method}(std::function<{resp}(const {req}&)> handler) {{")
        lines.append(f"        registerUnary<{req}, {resp}>(k{method}RequestSerialId,")
        lines.append(f"                                      k{method}ResponseSerialId, std::move(handler));")
