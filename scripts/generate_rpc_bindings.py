    lines.append("            if (!request.ParseFromString(payload)) {")
    lines.append("                return corpcron::RpcStreamResult{{")
    lines.append("                    corpcron::RpcDispatcher::error(BAD_REQUEST, \"parse request failed\")}};")
    lines.append("            }")
